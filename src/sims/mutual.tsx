import React, { useState, useEffect, useRef } from 'react';
import { Play, Pause, RotateCcw, Info, ArrowLeftRight } from 'lucide-react';

const MutualInductanceSimulation = () => {
  // Physical parameters
  const [r1, setR1] = useState(0.02); // Radius of inner coil S1 (m)
  const [r2, setR2] = useState(0.05); // Radius of outer coil S2 (m)
  const [length, setLength] = useState(0.20); // Length of both coils (m)
  const [N1, setN1] = useState(300); // Turns of inner coil S1
  const [N2, setN2] = useState(300); // Turns of outer coil S2
  
  // Electrical parameters
  const [I0, setI0] = useState(5.0); // Peak current (A)
  const [freq, setFreq] = useState(1.0); // Frequency of AC (Hz)
  const [primaryCoil, setPrimaryCoil] = useState('outer'); // 'outer' (S2) or 'inner' (S1)

  // Simulation state
  const [isPlaying, setIsPlaying] = useState(true);
  const [time, setTime] = useState(0);
  const [currentB, setCurrentB] = useState(0); // For visualizing B-field

  // Refs for animation loop and graphing
  const requestRef = useRef<any>(null);
  const timeRef = useRef(0);
  const canvasRef = useRef(null);
  
  // Constants
  const MU_0 = 4 * Math.PI * 1e-7; // Permeability of free space
  const HISTORY_LENGTH = 400; // Number of points in graph

  // History buffer for the oscilloscope
  const historyRef = useRef({
    i_primary: Array(HISTORY_LENGTH).fill(0),
    emf_secondary: Array(HISTORY_LENGTH).fill(0)
  });

  // Calculate Mutual Inductance (M)
  // According to NCERT 6.7.1, M12 = M21 = M. 
  // It ALWAYS depends on the inner radius r1^2 because if S1 is primary, 
  // its B-field is only inside r1. If S2 is primary, S1 only captures flux over r1.
  const calculateM = () => {
    return (MU_0 * N1 * N2 * Math.PI * Math.pow(r1, 2)) / length;
  };

  const M = calculateM();

  // Animation Loop
  const animate = (t) => {
    if (isPlaying) {
      // Increment time
      timeRef.current += 0.015;
      
      const tNow = timeRef.current;
      const omega = 2 * Math.PI * freq;
      
      // I_p(t) = I0 * sin(omega * t)
      const currentIp = I0 * Math.sin(omega * tNow);
      
      // EMF_s(t) = -M * dIp/dt = -M * I0 * omega * cos(omega * t)
      const currentEMF = -M * I0 * omega * Math.cos(omega * tNow);

      // Magnetic Field generated by the primary coil
      let B_field = 0;
      if (primaryCoil === 'outer') {
        B_field = MU_0 * (N2 / length) * currentIp;
      } else {
        B_field = MU_0 * (N1 / length) * currentIp;
      }
      
      setCurrentB(B_field);
      setTime(tNow);

      // Shift history arrays and push new values
      historyRef.current.i_primary.shift();
      historyRef.current.i_primary.push(currentIp);
      
      historyRef.current.emf_secondary.shift();
      historyRef.current.emf_secondary.push(currentEMF);

      drawGraph();
    }
    requestRef.current = requestAnimationFrame(animate);
  };

  useEffect(() => {
    requestRef.current = requestAnimationFrame(animate);
    return () => cancelAnimationFrame(requestRef.current);
  }, [isPlaying, M, I0, freq, primaryCoil]); // Re-bind if M, inputs, or source changes

  // Oscilloscope Drawing Logic
  const drawGraph = () => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    const width = canvas.width;
    const height = canvas.height;

    ctx.clearRect(0, 0, width, height);

    // Draw Grid & Axes
    ctx.strokeStyle = '#334155';
    ctx.lineWidth = 1;
    ctx.beginPath();
    ctx.moveTo(0, height / 2);
    ctx.lineTo(width, height / 2);
    ctx.stroke();

    // Determine max values for dynamic scaling
    const maxI = 10; 
    const dynamicMaxEMF = M * I0 * 2 * Math.PI * freq * 1.5; 
    const yscaleEMF = height / 2 / (dynamicMaxEMF < 0.01 ? 0.01 : dynamicMaxEMF);
    const yscaleI = height / 2 / (maxI * 1.2);

    const data = historyRef.current;
    const dx = width / HISTORY_LENGTH;

    // Set colors based on which coil is primary
    const colorI = primaryCoil === 'outer' ? '#3b82f6' : '#ef4444'; // Blue for outer, Red for inner
    const colorEMF = primaryCoil === 'outer' ? '#ef4444' : '#3b82f6';

    // Draw Primary Current
    ctx.strokeStyle = colorI;
    ctx.lineWidth = 2;
    ctx.beginPath();
    for (let i = 0; i < HISTORY_LENGTH; i++) {
      const x = i * dx;
      const y = height / 2 - (data.i_primary[i] * yscaleI);
      if (i === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    }
    ctx.stroke();

    // Draw Secondary Induced Voltage
    ctx.strokeStyle = colorEMF;
    ctx.lineWidth = 2;
    ctx.beginPath();
    for (let i = 0; i < HISTORY_LENGTH; i++) {
      const x = i * dx;
      const y = height / 2 - (data.emf_secondary[i] * yscaleEMF);
      if (i === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    }
    ctx.stroke();
  };

  // Ensure initial draw
  useEffect(() => {
    drawGraph();
  }, []);

  const resetSimulation = () => {
    timeRef.current = 0;
    historyRef.current.i_primary.fill(0);
    historyRef.current.emf_secondary.fill(0);
    setTime(0);
    setCurrentB(0);
    drawGraph();
  };

  // Handle switching power source
  const togglePrimaryCoil = (coil) => {
    setPrimaryCoil(coil);
    resetSimulation();
  };

  // Helper to draw coil loops in SVG
  const generateCoilSVG = (radius, turnsScale, color, yOffset = 0) => {
    const loops = [];
    const numLoops = Math.min(Math.floor(turnsScale / 10), 40); 
    const spacing = 360 / numLoops;
    
    for(let i = 0; i <= numLoops; i++) {
      const cx = 70 + (i * spacing);
      loops.push(
        <ellipse 
          key={i} 
          cx={cx} 
          cy={100 + yOffset} 
          rx={spacing * 0.4} 
          ry={radius} 
          fill="none" 
          stroke={color} 
          strokeWidth="2"
          opacity="0.8"
        />
      );
    }
    return loops;
  };

  // SVG Visual variables based on state
  const bRadius = primaryCoil === 'outer' ? r2 * 800 : r1 * 800;
  const bColor = primaryCoil === 'outer' ? '#3b82f6' : '#ef4444';

  return (
    <div className="flex flex-col md:flex-row w-full min-h-[36rem] bg-slate-900 text-slate-100 font-sans">
      
      {/* Left Column: Visualization & Theory */}
      <div className="flex-1 flex flex-col p-4 md:p-6 border-r border-slate-700 overflow-y-auto">
        <div className="mb-6">
          <h1 className="text-2xl font-bold text-white flex items-center gap-2 mb-2">
            Mutual Inductance
            <span className="text-sm font-normal px-2 py-1 bg-indigo-500/20 text-indigo-300 rounded-full border border-indigo-500/30">
              Reciprocity Theorem (M₁₂ = M₂₁)
            </span>
          </h1>
          <p className="text-slate-400 text-sm">
            Toggle the battery connection to see how alternating current in one coil induces an electromotive force (emf) in the other. Notice that the Mutual Inductance ($M$) remains perfectly identical regardless of which coil acts as the source!
          </p>
        </div>

        {/* 2D Interactive Solenoid Visualization */}
        <div className="bg-slate-800 rounded-xl border border-slate-700 p-4 mb-6 relative overflow-hidden flex flex-col items-center shadow-lg">
          <div className="flex justify-between w-full items-center mb-2">
            <h3 className="text-xs uppercase tracking-wider text-slate-500 font-semibold">Live Visualizer</h3>
            <div className="flex bg-slate-900 rounded-lg p-1 border border-slate-700">
              <button 
                onClick={() => togglePrimaryCoil('outer')}
                className={`px-3 py-1 text-xs font-semibold rounded-md transition-colors ${primaryCoil === 'outer' ? 'bg-blue-600 text-white' : 'text-slate-400 hover:text-white'}`}
              >
                Power Outer (S₂)
              </button>
              <button 
                onClick={() => togglePrimaryCoil('inner')}
                className={`px-3 py-1 text-xs font-semibold rounded-md transition-colors ${primaryCoil === 'inner' ? 'bg-red-600 text-white' : 'text-slate-400 hover:text-white'}`}
              >
                Power Inner (S₁)
              </button>
            </div>
          </div>
          
          <svg viewBox="0 0 500 200" className="w-full h-auto max-h-64 object-contain">
            {/* Background Base */}
            <rect x="50" y="40" width="400" height="120" fill="#1e293b" rx="8" />

            {/* Dynamic B-Field Visualization */}
            <g opacity={Math.abs(currentB) * 1000000}> 
              <defs>
                <linearGradient id="bFieldGradient" x1="0%" y1="0%" x2="100%" y2="0%">
                  <stop offset="0%" stopColor={currentB > 0 ? "#10b981" : bColor} stopOpacity="0.1" />
                  <stop offset="50%" stopColor={currentB > 0 ? "#10b981" : bColor} stopOpacity="0.6" />
                  <stop offset="100%" stopColor={currentB > 0 ? "#10b981" : bColor} stopOpacity="0.1" />
                </linearGradient>
              </defs>
              <rect x="70" y={100 - bRadius} width="360" height={bRadius * 2} fill="url(#bFieldGradient)" />
              
              {/* Dynamic Direction Arrows */}
              <path 
                d={currentB > 0 ? "M 240 100 L 260 100 M 255 95 L 260 100 L 255 105" : "M 260 100 L 240 100 M 245 95 L 240 100 L 245 105"} 
                stroke={currentB > 0 ? "#10b981" : bColor} 
                strokeWidth="3" 
                fill="none" 
              />
              <path 
                d={currentB > 0 ? "M 140 100 L 160 100 M 155 95 L 160 100 L 155 105" : "M 160 100 L 140 100 M 145 95 L 140 100 L 145 105"} 
                stroke={currentB > 0 ? "#10b981" : bColor} 
                strokeWidth="3" 
                fill="none" 
              />
              <path 
                d={currentB > 0 ? "M 340 100 L 360 100 M 355 95 L 360 100 L 355 105" : "M 360 100 L 340 100 M 345 95 L 340 100 L 345 105"} 
                stroke={currentB > 0 ? "#10b981" : bColor} 
                strokeWidth="3" 
                fill="none" 
              />
            </g>

            {/* Inner Coil S1 (Red) */}
            <g>
              <rect x="70" y={100 - (r1 * 800)} width="360" height={r1 * 1600} fill="#fca5a5" opacity="0.1" />
              {generateCoilSVG(r1 * 800, N1, "#ef4444")}
              <text x="35" y={100 - (r1 * 800) - 10} fill="#ef4444" fontSize="12" fontWeight="bold">S₁ (Inner)</text>
              <path d={`M 70 ${100 + (r1 * 800)} L 50 ${100 + (r1 * 800)} L 50 180`} stroke="#ef4444" strokeWidth="2" fill="none" />
              <path d={`M 430 ${100 + (r1 * 800)} L 450 ${100 + (r1 * 800)} L 450 180`} stroke="#ef4444" strokeWidth="2" fill="none" />
              
              {primaryCoil === 'inner' ? (
                <g> {/* AC Source */}
                  <circle cx="250" cy="180" r="12" fill="#1e293b" stroke="#ef4444" strokeWidth="2" />
                  <path d="M 243 180 Q 246 175 250 180 T 257 180" stroke="#ef4444" strokeWidth="2" fill="none"/>
                </g>
              ) : (
                <g> {/* Galvanometer */}
                  <circle cx="250" cy="180" r="12" fill="#1e293b" stroke="#ef4444" strokeWidth="2" />
                  <text x="246" y="184" fill="#ef4444" fontSize="12" fontWeight="bold">G</text>
                </g>
              )}
              
              <path d="M 50 180 L 238 180" stroke="#ef4444" strokeWidth="2" fill="none"/>
              <path d="M 262 180 L 450 180" stroke="#ef4444" strokeWidth="2" fill="none"/>
            </g>

            {/* Outer Coil S2 (Blue) */}
            <g>
              <rect x="70" y={100 - (r2 * 800)} width="360" height={r2 * 1600} fill="#93c5fd" opacity="0.05" />
              {generateCoilSVG(r2 * 800, N2, "#3b82f6")}
              <text x="430" y={100 - (r2 * 800) - 10} fill="#3b82f6" fontSize="12" fontWeight="bold">S₂ (Outer)</text>
              <path d={`M 70 ${100 - (r2 * 800)} L 50 ${100 - (r2 * 800)} L 50 20`} stroke="#3b82f6" strokeWidth="2" fill="none" />
              <path d={`M 430 ${100 - (r2 * 800)} L 450 ${100 - (r2 * 800)} L 450 20`} stroke="#3b82f6" strokeWidth="2" fill="none" />
              
              {primaryCoil === 'outer' ? (
                <g> {/* AC Source */}
                  <circle cx="250" cy="20" r="12" fill="#1e293b" stroke="#3b82f6" strokeWidth="2" />
                  <path d="M 243 20 Q 246 15 250 20 T 257 20" stroke="#3b82f6" strokeWidth="2" fill="none"/>
                </g>
              ) : (
                <g> {/* Galvanometer */}
                  <circle cx="250" cy="20" r="12" fill="#1e293b" stroke="#3b82f6" strokeWidth="2" />
                  <text x="246" y="24" fill="#3b82f6" fontSize="12" fontWeight="bold">G</text>
                </g>
              )}

              <path d="M 50 20 L 238 20" stroke="#3b82f6" strokeWidth="2" fill="none"/>
              <path d="M 262 20 L 450 20" stroke="#3b82f6" strokeWidth="2" fill="none"/>
            </g>
          </svg>
        </div>

        {/* Live Mathematical Dashboard */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
          <div className="bg-slate-800 border border-slate-700 rounded-xl p-4 shadow-lg">
            <h3 className="text-xs uppercase tracking-wider text-slate-500 mb-3 font-semibold flex items-center gap-2">
              <Info size={14}/> Live Equations
            </h3>
            <div className="space-y-3 font-mono text-sm">
              <div className="flex justify-between items-center pb-2 border-b border-slate-700/50">
                <span className="text-slate-400">
                  {primaryCoil === 'outer' ? 'M₁₂' : 'M₂₁'} = (μ₀·N₁·N₂·π·r₁²) / l
                </span>
                <span className="text-emerald-400 font-bold">{(M * 1000).toFixed(4)} mH</span>
              </div>
              <div className="flex justify-between items-center pb-2 border-b border-slate-700/50">
                <span className="text-slate-400">
                  {primaryCoil === 'outer' ? 'I₂(t)' : 'I₁(t)'} = I₀·sin(ωt)
                </span>
                <span className={primaryCoil === 'outer' ? 'text-blue-400' : 'text-red-400'}>
                  {(I0 * Math.sin(2 * Math.PI * freq * time)).toFixed(2)} A
                </span>
              </div>
              <div className="flex justify-between items-center">
                <span className="text-slate-400">
                  {primaryCoil === 'outer' ? 'ε₁' : 'ε₂'} = -M·(dI/dt)
                </span>
                <span className={`font-bold ${primaryCoil === 'outer' ? 'text-red-400' : 'text-blue-400'}`}>
                  {(-M * I0 * 2 * Math.PI * freq * Math.cos(2 * Math.PI * freq * time)).toFixed(3)} V
                </span>
              </div>
            </div>
          </div>
          
          <div className="bg-slate-800 border border-slate-700 rounded-xl p-4 shadow-lg">
            <h3 className="text-xs uppercase tracking-wider text-slate-500 mb-3 font-semibold">
              Oscilloscope (Real-time)
            </h3>
            <div className="relative w-full h-32 bg-slate-900 rounded-lg overflow-hidden border border-slate-700">
              <canvas 
                ref={canvasRef} 
                width={800} 
                height={300} 
                className="w-full h-full object-cover"
              />
              <div className="absolute top-2 left-2 text-[10px] font-mono flex flex-col gap-1">
                <div className="flex items-center gap-1">
                  <div className={`w-2 h-2 rounded-full ${primaryCoil === 'outer' ? 'bg-blue-500' : 'bg-red-500'}`}></div> 
                  {primaryCoil === 'outer' ? 'I₂ (Source Current)' : 'I₁ (Source Current)'}
                </div>
                <div className="flex items-center gap-1">
                  <div className={`w-2 h-2 rounded-full ${primaryCoil === 'outer' ? 'bg-red-500' : 'bg-blue-500'}`}></div> 
                  {primaryCoil === 'outer' ? 'ε₁ (Induced EMF)' : 'ε₂ (Induced EMF)'}
                </div>
              </div>
            </div>
          </div>
        </div>

        {/* Theory Explanation */}
        <div className="bg-emerald-900/20 border border-emerald-500/30 rounded-xl p-4 mt-auto">
          <p className="text-sm text-emerald-200 leading-relaxed">
            <strong className="text-white">The Reciprocity Theorem (M₁₂ = M₂₁):</strong> Did you notice that the Mutual Inductance ($M$) equation <em>always</em> uses the smaller radius ($r_1^2$), regardless of which coil is powered? 
            If the outer coil ($S_2$) is the source, its magnetic field fills the whole outer cylinder, but the inner coil ($S_1$) only "catches" flux within its smaller area. 
            If the inner coil ($S_1$) is the source, its magnetic field is entirely confined inside itself, meaning the outer coil only experiences flux in that exact same smaller central core. Thus, the flux linkage is geometrically identical either way!
          </p>
        </div>
      </div>

      {/* Right Column: Control Panel */}
      <div className="w-full md:w-80 bg-slate-800 border-l border-slate-700 p-6 flex flex-col gap-6 shadow-xl z-10">
        
        {/* Playback Controls */}
        <div className="flex gap-2">
          <button 
            onClick={() => setIsPlaying(!isPlaying)}
            className="flex-1 flex items-center justify-center gap-2 py-3 rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white font-semibold transition-colors shadow-lg shadow-indigo-900/20"
          >
            {isPlaying ? <Pause size={18} fill="currentColor"/> : <Play size={18} fill="currentColor"/>}
            {isPlaying ? 'Pause' : 'Play'}
          </button>
          <button 
            onClick={resetSimulation}
            className="px-4 py-3 rounded-lg bg-slate-700 hover:bg-slate-600 text-white transition-colors flex items-center justify-center"
            title="Reset Simulation"
          >
            <RotateCcw size={18} />
          </button>
        </div>

        <div className="h-px w-full bg-slate-700"></div>

        {/* Geometric Sliders */}
        <div className="flex flex-col gap-4">
          <h3 className="text-xs uppercase tracking-wider text-slate-400 font-semibold flex justify-between">
            <span>Coil Geometry</span>
          </h3>

          <div className="flex flex-col gap-1">
            <div className="flex justify-between text-sm">
              <label className="text-slate-300">Inner Radius (r₁)</label>
              <span className="text-indigo-400 font-mono">{(r1 * 100).toFixed(1)} cm</span>
            </div>
            <input 
              type="range" min="0.01" max={r2 - 0.005} step="0.001" 
              value={r1} onChange={(e) => setR1(parseFloat(e.target.value))}
              className="w-full accent-indigo-500"
            />
          </div>

          <div className="flex flex-col gap-1">
            <div className="flex justify-between text-sm">
              <label className="text-slate-300">Outer Radius (r₂)</label>
              <span className="text-indigo-400 font-mono">{(r2 * 100).toFixed(1)} cm</span>
            </div>
            <input 
              type="range" min={r1 + 0.005} max="0.08" step="0.001" 
              value={r2} onChange={(e) => setR2(parseFloat(e.target.value))}
              className="w-full accent-indigo-500"
            />
          </div>

          <div className="flex flex-col gap-1">
            <div className="flex justify-between text-sm">
              <label className="text-slate-300">Length (l)</label>
              <span className="text-indigo-400 font-mono">{(length * 100).toFixed(0)} cm</span>
            </div>
            <input 
              type="range" min="0.10" max="0.50" step="0.01" 
              value={length} onChange={(e) => setLength(parseFloat(e.target.value))}
              className="w-full accent-indigo-500"
            />
          </div>
          
          <div className="grid grid-cols-2 gap-4">
             <div className="flex flex-col gap-1">
              <div className="flex justify-between text-sm">
                <label className="text-slate-300">N₁</label>
              </div>
              <input 
                type="number" min="100" max="2000" step="50"
                value={N1} onChange={(e) => setN1(parseFloat(e.target.value) || 100)}
                className="w-full bg-slate-900 border border-slate-600 rounded px-2 py-1 text-sm text-white font-mono focus:outline-none focus:border-indigo-500"
              />
            </div>
            <div className="flex flex-col gap-1">
              <div className="flex justify-between text-sm">
                <label className="text-slate-300">N₂</label>
              </div>
              <input 
                type="number" min="100" max="2000" step="50"
                value={N2} onChange={(e) => setN2(parseFloat(e.target.value) || 100)}
                className="w-full bg-slate-900 border border-slate-600 rounded px-2 py-1 text-sm text-white font-mono focus:outline-none focus:border-indigo-500"
              />
            </div>
          </div>
        </div>

        <div className="h-px w-full bg-slate-700"></div>

        {/* Input AC Current Sliders */}
        <div className="flex flex-col gap-4">
          <h3 className="text-xs uppercase tracking-wider text-slate-400 font-semibold">
            AC Source Controls
          </h3>
          
          <div className="flex flex-col gap-1">
            <div className="flex justify-between text-sm">
              <label className={primaryCoil === 'outer' ? 'text-blue-300' : 'text-red-300'}>Peak Current (I₀)</label>
              <span className="text-slate-300 font-mono">{I0.toFixed(1)} A</span>
            </div>
            <input 
              type="range" min="1.0" max="10.0" step="0.5" 
              value={I0} onChange={(e) => setI0(parseFloat(e.target.value))}
              className={`w-full ${primaryCoil === 'outer' ? 'accent-blue-500' : 'accent-red-500'}`}
            />
          </div>

          <div className="flex flex-col gap-1">
            <div className="flex justify-between text-sm">
              <label className={primaryCoil === 'outer' ? 'text-blue-300' : 'text-red-300'}>Frequency (f)</label>
              <span className="text-slate-300 font-mono">{freq.toFixed(1)} Hz</span>
            </div>
            <input 
              type="range" min="0.5" max="5.0" step="0.1" 
              value={freq} onChange={(e) => setFreq(parseFloat(e.target.value))}
              className={`w-full ${primaryCoil === 'outer' ? 'accent-blue-500' : 'accent-red-500'}`}
            />
          </div>
        </div>

      </div>
    </div>
  );
};

export default MutualInductanceSimulation;